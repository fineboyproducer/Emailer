-- Live registration + reminders (Emailer). Safe to re-run: everything is IF NOT EXISTS.
-- The app also runs this file automatically at startup, so running it by hand is optional.

-- One row per person per live session they registered for. A person registering for next
-- Friday's live is a new row; registering twice for the same Friday is a no-op.
create table if not exists live_registrations (
  id            bigint generated by default as identity primary key,
  contact_id    bigint references contacts(id) on delete set null,
  first_name    text not null,
  email         text not null,
  whatsapp      text,
  artist_name   text,
  event_name    text not null,
  event_date    date not null,                       -- the Friday (WAT) this registration is for
  registered_at timestamptz not null default now(),
  unsubscribed_at timestamptz,                       -- opted out of live reminders (does not touch campaigns)
  source        text not null default 'page'         -- 'page' (live page) | 'sync' (copied from the site's table)
);
create unique index if not exists idx_live_reg_email_date on live_registrations (lower(email), event_date);
create index if not exists idx_live_reg_event_date on live_registrations (event_date);
create index if not exists idx_live_reg_contact on live_registrations (contact_id);

-- One row per person per reminder. The unique key is what makes a double send impossible,
-- even if two runs overlap or a run crashes and retries.
create table if not exists live_reminder_log (
  id                  bigint generated by default as identity primary key,
  registration_id     bigint not null references live_registrations(id) on delete cascade,
  kind                text not null check (kind in ('confirm', '24h', '1h', 'live')),
  status              text not null default 'pending' check (status in ('pending', 'sent', 'failed')),
  attempts            int not null default 0,
  provider_message_id text,
  error               text,
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now(),
  sent_at             timestamptz,
  unique (registration_id, kind)
);
create index if not exists idx_live_reminder_log_status on live_reminder_log (status);
