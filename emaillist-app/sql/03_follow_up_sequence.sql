-- Follow-up email sequence (Emailer). Safe to re-run: everything is IF NOT EXISTS.
-- The app runs this file automatically at startup, so running it by hand is optional.

-- Who has paid for what. Rows arrive from the Paystack webhook, or by hand (see docs/follow-up-sequence-runbook.md).
-- A buyer stops getting sales emails for the lead track and starts that product's buyer track.
create table if not exists sequence_purchases (
  id           bigint generated by default as identity primary key,
  email        text not null,
  product      text not null check (product in ('blueprint', 'bundle', 'agi')),
  reference    text,                                   -- the Paystack payment reference, when known
  amount_kobo  bigint,
  source       text not null default 'manual',         -- 'paystack' or 'manual'
  purchased_at timestamptz not null default now()
);
create unique index if not exists idx_sequence_purchases_email_product on sequence_purchases (lower(email), product);
create unique index if not exists idx_sequence_purchases_reference on sequence_purchases (reference) where reference is not null;

-- One row per person per email in the sequence. The unique key makes a double send impossible,
-- even if two runs overlap or a run crashes and retries.
create table if not exists sequence_log (
  id                  bigint generated by default as identity primary key,
  email               text not null,                   -- stored lower-case
  step                text not null,                   -- B1, U2, A3, C1 ... (see src/sequence/emails.md)
  status              text not null default 'pending' check (status in ('pending', 'sent', 'failed')),
  attempts            int not null default 0,
  provider_message_id text,
  error               text,
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now(),
  sent_at             timestamptz,
  unique (email, step)
);
create index if not exists idx_sequence_log_status on sequence_log (status);
create index if not exists idx_sequence_log_sent_at on sequence_log (sent_at);
